#!/usr/bin/env python3
"""Generate runtime capability tables from canonical contracts; --check never writes.

Run from any directory: python scripts/generate_capabilities.py [--core ../whale-core] [--check]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Existing default pairing policy; new supported scopes require explicit opt-in.
LEGACY_PAIRING = (
    "screen.context.read", "screen.history.search", "screen.evidence.read",
    "screen.live.subscribe", "phone.notification.post", "phone.notification.read",
    "phone.call.ring", "phone.call.audio", "phone.device.safe_action",
)
OPT_IN_DECLARATIONS = {"device.agent.output.read"}


def capability_tables(root: Path) -> dict[str, tuple[str, ...]]:
    def values(message: str, field: str, *, array: bool = False) -> tuple[str, ...]:
        schema = json.loads((root / "contracts/v1/messages" / f"{message}.schema.json").read_text(encoding="utf-8"))
        node = schema["properties"]["payload"]["properties"][field]
        result = (node["items"] if array else node)["enum"]
        if not result or any(not isinstance(v, str) for v in result) or len(result) != len(set(result)):
            raise ValueError(f"{message}.{field}: expected nonempty unique string enum")
        return tuple(result)

    all_caps = values("device.hello", "capabilities", array=True)
    accepted = values("device.hello_ack", "accepted_capabilities", array=True)
    if set(accepted) != set(all_caps):
        raise ValueError("device.hello and hello_ack capability enums disagree")
    action = values("action.request", "capability")
    query = values("sensor.query", "operation")
    authorized = values("action.request", "authorized_scope", array=True)
    if set(authorized) != set(action):
        raise ValueError("action capability and authorized_scope disagree")
    if not (set(action) | set(query) | set(LEGACY_PAIRING) | OPT_IN_DECLARATIONS) <= set(all_caps):
        raise ValueError("operation or default scope missing from device.hello")
    return {
        "DEVICE_CAPABILITIES": all_caps,
        "ACTION_CAPABILITIES": action,
        "QUERY_CAPABILITIES": query,
        "DEFAULT_DECLARED_CAPABILITIES": tuple(v for v in all_caps if v not in OPT_IN_DECLARATIONS),
        "DEFAULT_PAIRING_CAPABILITIES": LEGACY_PAIRING,
    }


def python_source(tables: dict[str, tuple[str, ...]]) -> str:
    text = '# Generated by whale-mobile/scripts/generate_capabilities.py; do not edit.\n'
    for name, entries in tables.items():
        text += f'\n{name}: tuple[str, ...] = (\n'
        text += ''.join(f'    {json.dumps(value)},\n' for value in entries)
        text += ')\n'
    return text


def outputs(root: Path, core: Path | None = None) -> dict[Path, str]:
    tables = capability_tables(root)
    kotlin = '// Generated by scripts/generate_capabilities.py; do not edit.\n'
    kotlin += 'package com.wangfanlab.whale.transport\n\nobject ProtocolCapabilities {\n'
    for name in ("DEVICE_CAPABILITIES", "ACTION_CAPABILITIES", "QUERY_CAPABILITIES"):
        kotlin += f'    val {name}: Set<String> = setOf(\n'
        kotlin += ''.join(f'        {json.dumps(value)},\n' for value in tables[name])
        kotlin += '    )\n'
    kotlin += '}\n'
    dart = '// Generated by scripts/generate_capabilities.py; do not edit.\n'
    dart += 'const List<String> defaultDeclaredCapabilities = [\n'
    dart += ''.join(f'  {json.dumps(value)},\n' for value in tables['DEFAULT_DECLARED_CAPABILITIES'])
    dart += '];\n'
    result = {
        root / 'server/protocol_capabilities.py': python_source(tables),
        root / 'app/android/app/src/main/kotlin/com/wangfanlab/whale/transport/ProtocolCapabilities.kt': kotlin,
        root / 'app/lib/transport/protocol_capabilities.dart': dart,
    }
    if core is not None:
        if not (core / 'src/whale_core/devices').is_dir():
            raise ValueError('Core checkout missing src/whale_core/devices')
        result[core / 'src/whale_core/devices/capabilities.py'] = python_source(tables)
    return result


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--core', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    try:
        targets = outputs(ROOT, args.core)
    except (ValueError, KeyError, OSError) as exc:
        parser.error(str(exc))
    stale = []
    for path, expected in targets.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != expected:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding='utf-8', newline='\n')
    for path in stale:
        print(f'STALE: {path}')
    if stale:
        print('Run generate_capabilities.py without --check, then commit generated files together.')
        return 1
    print(f'OK: {len(targets)} capability tables {"checked" if args.check else "generated"}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
